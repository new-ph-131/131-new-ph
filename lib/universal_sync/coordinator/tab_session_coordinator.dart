import "dart:math";
import "package:flutter/foundation.dart";

/// TabSessionCoordinator: Manages multi-tab browser isolation and origin tracking.
/// Generates an immutable session ID for each tab/device to suppress self-echoes
/// and allow concurrent execution across Web 1, Web 2, Web 3, and Mobile App.
class TabSessionCoordinator {
  static final TabSessionCoordinator instance = TabSessionCoordinator._internal();
  TabSessionCoordinator._internal();

  static final String _sessionId = _generateSessionId();

  static String get sessionId => _sessionId;

  static String _generateSessionId() {
    final rand = Random().nextInt(999999).toString().padLeft(6, "0");
    final prefix = kIsWeb ? "WEB-TAB" : "APP-MOB";
    return "$prefix-${DateTime.now().millisecondsSinceEpoch % 1000000}-$rand";
  }

  /// Returns true if an incoming event was generated by this exact tab/device instance
  static bool isSelfOrigin(String clientSource) {
    if (clientSource.trim().isEmpty) return false;
    return clientSource.trim().toUpperCase() == _sessionId.trim().toUpperCase();
  }
}
